"""Bake one OpenCode 2 artifact: this package and one artifact package, side by side under a parent package as they
sit in the source tree, zipped into a standalone executable with a validated lever set and version.

Runs inside blizzard-mock's own venv at emit time, never inside an artifact."""

from __future__ import annotations

import shutil
import tempfile
import zipapp
from pathlib import Path

from .levers import Lever

DEFAULT_VERSION = "2.1.4"

_CORE_ROOT = Path(__file__).resolve().parent
#: The parent package an artifact's two packages sit under, as ``blizzard_mock.harness`` holds them in the tree.
_PARENT = "opencode2"
#: Never copied into an artifact: the emit modules, and ``_baked.py`` (rendered fresh for each artifact).
_EXCLUDED_MEMBERS = {"emit.py", "_baked.py", "__pycache__"}


def _copy_package(source_root: Path, destination: Path) -> None:
    """Every top-level member of the package at ``source_root``, discovered rather than hand-listed so a module
    added later cannot silently go missing from an artifact."""
    destination.mkdir()
    for entry in sorted(source_root.iterdir()):
        if entry.name in _EXCLUDED_MEMBERS or not (entry.is_dir() or entry.suffix == ".py"):
            continue
        if entry.is_dir():
            shutil.copytree(entry, destination / entry.name, ignore=shutil.ignore_patterns("__pycache__"))
        else:
            shutil.copy2(entry, destination / entry.name)


def bake(out: Path, package_root: Path, *, levers: frozenset[Lever], version: str) -> None:
    """Write an executable zipapp to ``out`` that runs ``package_root``'s ``cli.main()``. ``out``'s parent must
    exist."""
    with tempfile.TemporaryDirectory() as scratch_name:
        scratch = Path(scratch_name)
        parent = scratch / _PARENT
        parent.mkdir()
        (parent / "__init__.py").write_text('"""An emitted OpenCode 2 artifact."""\n')
        _copy_package(_CORE_ROOT, parent / _CORE_ROOT.name)
        _copy_package(package_root, parent / package_root.name)
        (parent / package_root.name / "_baked.py").write_text(render_baked(levers, version))
        # Not zipapp's own `main=`: its generated shim drops `cli.main()`'s return value.
        entry = f"{_PARENT}.{package_root.name}.cli"
        (scratch / "__main__.py").write_text(f"import sys\n\nimport {entry}\n\nsys.exit({entry}.main())\n")
        zipapp.create_archive(scratch, target=out, interpreter="/usr/bin/env python3")
    out.chmod(0o755)


def render_baked(levers: frozenset[Lever], version: str) -> str:
    """The ``_baked.py`` an artifact is emitted with: its fixed lever set and version."""
    names = ", ".join(f"Lever.{lever.name}" for lever in sorted(levers, key=lambda member: member.name))
    lever_expr = f"frozenset({{{names}}})" if names else "frozenset()"
    return (
        '"""Generated by emit.py — this artifact\'s fixed, immutable configuration."""\n'
        "from __future__ import annotations\n\n"
        "from ..opencode2_core.levers import Lever\n\n"
        f"LEVERS: frozenset[Lever] = {lever_expr}\n"
        f"VERSION: str = {version!r}\n"
    )


__all__ = ["DEFAULT_VERSION", "bake", "render_baked"]
