"""Bake a validated lever set into a standalone zipapp fake-OpenCode-2 binary.

Runs inside blizzard-mock's own venv at ``mock-opencode-2 emit`` time, never inside the emitted artifact."""

from __future__ import annotations

import shutil
import tempfile
import zipapp
from pathlib import Path

from .levers import Lever

_PACKAGE_ROOT = Path(__file__).resolve().parent
DEFAULT_VERSION = "2.1.4"

#: Never copied into the artifact: this module, and ``_baked.py`` (regenerated fresh below).
_EXCLUDED_MEMBERS = {"emit.py", "_baked.py", "__pycache__"}


def _discover_source_members() -> tuple[str, ...]:
    """Every top-level package member the artifact ships, discovered rather than hand-listed so a module added
    later cannot silently go missing from the zipapp."""
    return tuple(
        sorted(
            entry.name
            for entry in _PACKAGE_ROOT.iterdir()
            if entry.name not in _EXCLUDED_MEMBERS and (entry.is_dir() or entry.suffix == ".py")
        )
    )


def emit(out: Path, *, levers: frozenset[Lever] = frozenset(), version: str = DEFAULT_VERSION) -> None:
    """Write an executable zipapp to ``out``, baked with the given lever set. ``out``'s parent must exist."""
    with tempfile.TemporaryDirectory() as scratch_name:
        scratch = Path(scratch_name)
        staging = scratch / "opencode2_surface"
        staging.mkdir()
        for name in _discover_source_members():
            source = _PACKAGE_ROOT / name
            destination = staging / name
            if source.is_dir():
                shutil.copytree(source, destination, ignore=shutil.ignore_patterns("__pycache__"))
            else:
                shutil.copy2(source, destination)
        (staging / "_baked.py").write_text(_render_baked(levers, version))
        # Not zipapp's own `main=`: its generated shim drops `cli.main()`'s return value.
        (scratch / "__main__.py").write_text(
            "import sys\n\nimport opencode2_surface.cli\n\nsys.exit(opencode2_surface.cli.main())\n"
        )
        zipapp.create_archive(scratch, target=out, interpreter="/usr/bin/env python3")
    out.chmod(0o755)


def _render_baked(levers: frozenset[Lever], version: str) -> str:
    names = ", ".join(f"Lever.{lever.name}" for lever in sorted(levers, key=lambda member: member.name))
    lever_expr = f"frozenset({{{names}}})" if names else "frozenset()"
    return (
        '"""Generated by emit.py — this artifact\'s fixed, immutable configuration."""\n'
        "from __future__ import annotations\n\n"
        "from .levers import Lever\n\n"
        f"LEVERS: frozenset[Lever] = {lever_expr}\n"
        f"VERSION: str = {version!r}\n"
    )


__all__ = ["DEFAULT_VERSION", "emit"]
